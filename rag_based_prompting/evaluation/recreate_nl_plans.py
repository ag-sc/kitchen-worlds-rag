import ast
from pathlib import Path

import pandas as pd
from tqdm import tqdm

from run_experiment import EXP_PATH

PLAN_COLUMNS = ['step_idx', 'nl_desc']


def recreate_plans_for_all_experiments():
    experiment_metadata = pd.read_csv(EXP_PATH, index_col="name")
    for name, row in tqdm(experiment_metadata.iterrows(),
                          f"Recreating the plans for all {len(experiment_metadata)} experiments..."):
        parent_folder = Path(__file__).parent / ".." / "eval_scenarios" / row["subfolder"]
        for exp_folder in parent_folder.iterdir():
            if not exp_folder.is_dir():
                continue
            res_csv = list(exp_folder.glob("seed_*.csv"))
            df_nl_plan = pd.DataFrame(columns=PLAN_COLUMNS)
            if len(res_csv) == 1:
                csv_path = res_csv[0]
                prev_idx = 0
                prev_step = ""
                for row in pd.read_csv(csv_path).iloc[:-1].itertuples(index=False):
                    idx, step = process_plan_string(row.planning_node)
                    if idx == prev_idx and step == prev_step:
                        continue
                    new_row = {
                        PLAN_COLUMNS[0]: idx,
                        PLAN_COLUMNS[1]: step,
                    }
                    df_nl_plan = pd.concat([df_nl_plan, pd.DataFrame([new_row])], ignore_index=True)
                    prev_idx = idx
                    prev_step = step
                df_nl_plan.to_csv(f'{exp_folder / "nl_plan.csv"}', index=False)
            else:
                print(f"Warning: {exp_folder} has {len(res_csv)} matching csv files")


# turn strings like "1_a_['open', 'fridge door']" into a tuple (1, 'open fridge door')
def process_plan_string(plan: str) -> (int, str):
    step_str, _, action_str = plan.split("_", 2)
    step = int(step_str)
    action_list = ast.literal_eval(action_str)
    action = ", ".join(action_list)
    return step, f"({action})"


if __name__ == "__main__":
    recreate_plans_for_all_experiments()
    print('\nFinished recreating the NL plans generated by the first LLM iteration')
